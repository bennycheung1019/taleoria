const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(require('node:path').join(__dirname,'../app.js'),'utf8');
const handler=source.match(/function handleActionKeydown\(e\) \{[\s\S]*?\n\}/)[0];
let sent=0,captured='';const input={value:'查看安雅\n保留原文'},button={disabled:false,click(){sent++;captured=input.value;}};
const context=vm.createContext({actionComposing:false,actionCompositionEnded:-Infinity,$:id=>id==='sendAction'?button:input});
vm.runInContext(handler,context);
const key=(changes={})=>{let prevented=false;context.handleActionKeydown({key:'Enter',timeStamp:1000,preventDefault(){prevented=true;},...changes});return prevented;};
assert.equal(key(),true);assert.equal(sent,1);assert.equal(captured,'查看安雅\n保留原文');
assert.equal(key({shiftKey:true}),false);assert.equal(sent,1);
assert.equal(key({isComposing:true}),false);assert.equal(key({keyCode:229}),false);
context.actionComposing=true;assert.equal(key(),false);context.actionComposing=false;
context.actionCompositionEnded=980;assert.equal(key(),false);assert.equal(sent,1);
assert.equal(key({timeStamp:1100}),true);assert.equal(sent,2);
assert.equal(key({repeat:true,timeStamp:1200}),true);assert.equal(sent,2);
button.disabled=true;assert.equal(key({timeStamp:1300}),true);assert.equal(sent,2);
button.disabled=false;input.value=' \n ';assert.equal(key({timeStamp:1400}),true);assert.equal(sent,2);
assert.equal(key({key:'a'}),false);assert.equal(key({altKey:true}),false);
assert.ok(source.includes("addEventListener('compositionstart'"));assert.ok(source.includes("addEventListener('compositionend'"));
console.log('Composer keys: Enter sends once; Shift+Enter, IME selection/end, held keys, disabled and empty input are safe; original multiline text preserved.');
